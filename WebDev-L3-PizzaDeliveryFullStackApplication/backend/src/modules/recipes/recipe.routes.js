import {Router} from "express";
import {authenticate,authorize} from "../auth/auth.middleware.js";
import {validate} from "../../middleware/validate.js";
import * as controller from "./recipe.controller.js";
import {recipeListSchema,recipeParamsSchema,recipeSaveSchema} from "./recipe.validation.js";
const router=Router();router.use(authenticate,authorize("admin"));
router.get("/",validate(recipeListSchema),controller.list);
router.get("/:productId",validate(recipeParamsSchema),controller.get);
router.put("/:productId",validate(recipeSaveSchema),controller.save);
export default router;
